def upsert(rows: list[dict[str, str]], incoming: dict[str, str], key: str = "id") -> None:
    for index, row in enumerate(rows):
        if row.get(key) == incoming[key]:
            rows[index] = {**row, **incoming}
            return
    rows.append(incoming)


def main() -> None:
    sources = read_csv(CURATED / "sources.csv")
    organizations = read_csv(CURATED / "organizations.csv")
    projects = read_csv(CURATED / "projects.csv")
    links = read_csv(CURATED / "project_organizations.csv")
    claims = read_csv(CURATED / "project_sources.csv")
    investments = read_csv(CURATED / "investments.csv")

    for source in SOURCES:
        upsert(sources, source)
    for org in ORGS:
        upsert(organizations, org)

    for factory in FACTORIES:
        sources_list = factory.pop("sources")
        org_id = factory.pop("org_id")
        upsert(projects, factory)

        org_link = {
            "project_id": factory["id"],
            "org_id": org_id,
            "role": "operator",
            "share_pct": "",
            "start_year": "",
            "end_year": "",
            "source_id": sources_list[0][0],
            "notes": "",
        }
        upsert(links, org_link, key="project_id")

        # Replace this project's claims so a rerun removes stale source links.
        claims[:] = [row for row in claims if row["project_id"] != factory["id"]]

        for source_id, claim in sources_list:
            claim_row = {
                "project_id": factory["id"],
                "source_id": source_id,
                "claim": claim,
                "claim_value": "",
                "claim_date": "",
                "notes": "",
            }
            if not any(
                row["project_id"] == claim_row["project_id"]
                and row["source_id"] == claim_row["source_id"]
                for row in claims
            ):
                claims.append(claim_row)

    for inv_id, project_id, org_id, amount, currency, amount_idr_t, year, stage, instrument, source_id, notes in INVESTMENTS:
        upsert(
            investments,
            {
                "id": inv_id,
                "project_id": project_id,
                "investor_org_id": org_id,
                "amount": amount,
                "currency": currency,
                "amount_idr_t": amount_idr_t,
                "fx_date": "2026-11-08",
                "year": year,
                "stage": stage,
                "instrument": instrument,
                "share_pct": "",
                "source_id": source_id,
                "notes": notes,
            },
        )

    write_csv(CURATED / "sources.csv", SOURCE_FIELDS, sources)
    write_csv(CURATED / "organizations.csv", ORG_FIELDS, organizations)
    write_csv(CURATED / "projects.csv", PROJECT_FIELDS, projects)
    write_csv(CURATED / "project_organizations.csv", PROJECT_ORG_FIELDS, links)
    write_csv(CURATED / "project_sources.csv", PROJECT_SOURCE_FIELDS, claims)
    write_csv(CURATED / "investments.csv", INVESTMENT_FIELDS, investments)

    print(
        f"OK: {len(FACTORIES)} factories, {len(SOURCES)} sources, "
        f"{len(ORGS)} organisations, {len(INVESTMENTS)} investments"
    )


if __name__ == "__main__":
    main()
